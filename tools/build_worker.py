"""Create a dependency-free classic Worker from the tested ES module sources.
No Node/build dependencies. Run after changing either numerical model.
"""
from pathlib import Path
import re,hashlib
root=Path(__file__).resolve().parents[1]/'web'
def wrap(name,source,imports=''):
    names=re.findall(r'^export\s+(?:function|const)\s+(\w+)',source,re.M)
    # RMOON shares one declaration with DEG.
    if name=='mission': names.append('RMOON')
    source=re.sub(r'^import .*?;\s*\n',imports+'\n',source,flags=re.M)
    source=re.sub(r'^export\s+','',source,flags=re.M)
    return f'const __{name}=(()=>{{\n{source}\nreturn {{'+','.join(names)+'};\n})();\n'
solar=(root/'solar-model.js').read_text();mission=(root/'mission-model.js').read_text();decision=(root/'decision-model.js').read_text();worker=(root/'worker.js').read_text()
result='// Generated by tools/build_worker.py. Edit the module sources, not this file.\n'
result+='// Source digest '+hashlib.sha256((solar+mission+decision+worker).encode()).hexdigest()+'\n'
result+=wrap('solar',solar)
result+=wrap('mission',mission,'const {computeScenario,horizonForSite,interpolateHorizon,discFraction}=__solar;')
result+=wrap('decision',decision)
result+='const {computeMission}=__mission;\nconst {buildSearchPlan}=__decision;\n'
result+=re.sub(r'^import .*?;','',worker,flags=re.M)
(root/'worker.bundle.js').write_text(result)
print('Built worker.bundle.js',len(result),'bytes')
